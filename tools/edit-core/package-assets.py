#!/usr/bin/env python3
"""Package a verified wasm-bindgen web build; never accepts or processes mapping data."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys


def package(source: Path, destination: Path, manifest: Path) -> None:
    wasm = source / "braid_ferrule_edit_wasm_bg.wasm"
    glue = source / "braid_ferrule_edit_wasm.js"
    subprocess.run([sys.executable, str(Path(__file__).with_name("check-imports.py")), str(wasm)], check=True)
    if "qualify_checkpoint" in glue.read_text():
        raise ValueError("The qualification export must not ship in the application.")
    destination.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(wasm, destination / "core.wasm")
    shutil.copyfile(glue, destination / "core.js")
    shutil.copyfile(Path(__file__).with_name("worker.js"), destination / "worker.js")
    notices = Path(__file__).resolve().parents[2] / "engines/ferrule-host/third-party"
    shutil.copytree(notices, destination / "third-party", dirs_exist_ok=True)
    integrity = "sha256-" + base64.b64encode(hashlib.sha256(wasm.read_bytes()).digest()).decode()
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text("// Generated by tools/edit-core/package-assets.py. No mapping data.\n"
                        + "export const editAssets = {\n"
                        + "  integrity: " + json.dumps(integrity) + ",\n"
                        + '  wasm: "/edit/core.wasm",\n  worker: "/edit/worker.js",\n} as const;\n')


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    parser.add_argument("manifest", type=Path)
    args = parser.parse_args()
    package(args.source, args.destination, args.manifest)
